import * as vscode from "vscode";
import {
  editPolicyFor,
  type RGWBundle,
  type RGWRequirement,
  type RGWTraceabilityEntry,
} from "../rgwIo";
import type { RequirementEntry, RequirementGroup } from "./messages";

const path = require("path");

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

/**
 * JSON-encode a state object for embedding inside `<script>...</script>`.
 * Escapes `<`, `>`, and U+2028/U+2029 so the literal can't break out of the
 * script tag (a requirement title containing `</script>` would otherwise
 * terminate the block early). The output remains valid JSON.
 */
function serializeStateForScriptTag(state: unknown): string {
  return JSON.stringify(state)
    .replace(/</g, "\\u003c")
    .replace(/>/g, "\\u003e")
    .replace(/\u2028/g, "\\u2028")
    .replace(/\u2029/g, "\\u2029");
}

/**
 * Flatten the bundle into ordered groups keyed by `function || unit ||
 * source`. Used by both the TS-side initial render and (sent verbatim to
 * the webview) the post-save / post-infer refresh path, so the webview can
 * rebuild the cards section via safe DOM APIs without receiving pre-built
 * HTML.
 */
export function groupRequirements(bundle: RGWBundle): RequirementGroup[] {
  const flat: RequirementEntry[] = [];
  for (const [source, bucket] of Object.entries(bundle.requirements)) {
    for (const [id, req] of Object.entries(bucket)) {
      flat.push({
        source,
        id,
        req,
        trace: bundle.traceability[id] ?? {
          unit: null,
          function: null,
          lines: null,
        },
      });
    }
  }

  const buckets: Record<string, RequirementEntry[]> = {};
  const order: string[] = [];
  for (const entry of flat) {
    const key =
      entry.trace.function || entry.trace.unit || entry.source || "Unknown";
    if (!buckets[key]) {
      buckets[key] = [];
      order.push(key);
    }
    buckets[key].push(entry);
  }

  return order.map((name) => ({ name, entries: buckets[name] }));
}

export function renderRequirementsBody(
  bundle: RGWBundle,
  unitsToFunctions: Record<string, string[]> | null
): string {
  const policy = editPolicyFor(bundle);
  let body = "";
  for (const group of groupRequirements(bundle)) {
    body += `<h2>${escapeHtml(group.name)}</h2>`;
    for (const entry of group.entries) {
      body += renderCard(entry, policy.bodiesEditable, unitsToFunctions);
    }
  }
  return body;
}

/**
 * Build the full webview HTML. Loads CSS + JS from the `webviews/` media
 * folder via webview-relative URIs (a generated nonce gates `<script>`
 * execution). Initial state is injected as a `window.__rgwState` blob the
 * script picks up on load.
 */
export function generateRequirementsHtml(
  webview: vscode.Webview,
  webviewBaseDir: string,
  nonce: string,
  bundle: RGWBundle,
  unitsToFunctions: Record<string, string[]> | null = null
): string {
  const policy = editPolicyFor(bundle);

  const cssUri = webview.asWebviewUri(
    vscode.Uri.file(path.join(webviewBaseDir, "css", "requirements.css"))
  );
  const scriptUri = webview.asWebviewUri(
    vscode.Uri.file(
      path.join(webviewBaseDir, "webviewScripts", "requirements.js")
    )
  );

  const bannerHtml = policy.bodiesEditable
    ? `<div class="banner banner-editable">Editable — these requirements were generated by Reqs2X. Changes are saved back into the RGW.</div>`
    : `<div class="banner banner-readonly">Only traceability information can be updated with requirements exported from an external source (Polarion, DOORS, ...). Otherwise re-import could conflict with local changes.</div>`;

  const body = renderRequirementsBody(bundle, unitsToFunctions);

  const initialState = {
    gatewayPath: bundle.gatewayPath,
    policy,
    mtimes: bundle.mtimes,
    requirements: bundle.requirements,
    traceability: bundle.traceability,
    unitsToFunctions,
  };

  const cspSource = webview.cspSource;
  return `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src ${cspSource}; script-src 'nonce-${nonce}';">
<title>Requirements</title>
<link rel="stylesheet" href="${cssUri}">
</head>
<body>
<h1>Requirements</h1>
<div id="rgw-pill" title="${escapeHtml(bundle.gatewayPath)}">RGW: ${escapeHtml(bundle.gatewayPath)}</div>
${bannerHtml}
<div id="save-toolbar">${policy.bodiesEditable ? `<button id="add-btn" title="Add a new requirement to this RGW.">+ Add requirement</button>` : ""}<button id="infer-btn" title="Use the configured LLM to infer the unit/function each requirement traces to.">✨ Infer traceability</button><button id="save-btn" disabled>Save changes</button></div>
<div id="search-bar"><input id="search-input" type="search" placeholder="Search…" /><select id="filter-unit" title="Filter by unit"></select><select id="filter-function" title="Filter by function"></select><span id="search-count"></span></div>
<div id="reqs-body">${body}</div>
<script nonce="${nonce}">window.__rgwState = ${serializeStateForScriptTag(initialState)};</script>
<script nonce="${nonce}" src="${scriptUri}"></script>
</body>
</html>`;
}

function renderCard(
  entry: {
    source: string;
    id: string;
    req: RGWRequirement;
    trace: RGWTraceabilityEntry;
  },
  editable: boolean,
  unitsToFunctions: Record<string, string[]> | null
): string {
  const idAttrs = `data-req-id="${escapeHtml(entry.id)}"`;
  const reqDis = editable ? "" : "disabled";
  const lastMod = entry.req.last_modified ?? "";

  const removeBtn = editable
    ? `<button class="req-remove-btn" data-action="remove" data-req-id="${escapeHtml(entry.id)}" title="Remove this requirement">×</button>`
    : "";

  // Search haystack: lowercased concat of fields the in-page filter
  // matches against. Kept as a data attribute so the script doesn't have
  // to read all the inputs on every keystroke.
  const haystack = [
    entry.id,
    entry.req.title ?? "",
    entry.req.description ?? "",
    entry.trace.unit ?? "",
    entry.trace.function ?? "",
  ]
    .join(" ")
    .toLowerCase();

  return `
    <div class="req" data-req-id="${escapeHtml(entry.id)}" data-haystack="${escapeHtml(haystack)}" data-trace-unit="${escapeHtml(entry.trace.unit ?? "")}" data-trace-function="${escapeHtml(entry.trace.function ?? "")}">
      <div class="req-header">
        <div class="req-id">${escapeHtml(entry.id)}</div>
        <div class="req-meta">${lastMod ? `modified: ${escapeHtml(lastMod)} · ` : ""}source: ${escapeHtml(entry.source)}${removeBtn ? ` ${removeBtn}` : ""}</div>
      </div>
      <div class="field">
        <label>Title</label>
        <input type="text" ${idAttrs} data-scope="req" data-field="title" value="${escapeHtml(entry.req.title ?? "")}" ${reqDis}>
      </div>
      <div class="field">
        <label>Description</label>
        <textarea ${idAttrs} data-scope="req" data-field="description" ${reqDis}>${escapeHtml(entry.req.description ?? "")}</textarea>
      </div>
      <div class="field trace-row">
        <div>
          <label>Traceability: unit</label>
          ${renderTraceField({
            field: "unit",
            current: entry.trace.unit ?? "",
            options: unitsToFunctions ? Object.keys(unitsToFunctions) : null,
            idAttrs,
          })}
        </div>
        <div>
          <label>Traceability: function</label>
          ${renderTraceField({
            field: "function",
            current: entry.trace.function ?? "",
            options: unitsToFunctions
              ? unitsToFunctions[entry.trace.unit ?? ""] ?? []
              : null,
            idAttrs,
          })}
        </div>
      </div>
      <div class="open-source-row">
        <button class="open-source-btn" data-action="open-source"${entry.trace.unit ? "" : " disabled"} title="Open the unit's source file at the function definition.">↗ Open source</button>
      </div>
    </div>
  `;
}

/**
 * Render a traceability field as either a free-text input (when `options` is
 * null — env data wasn't available) or a `<select>` dropdown with a "(none)"
 * entry. Preserves the current value as a synthetic "(not in env)" option if
 * it falls outside the known set, so legacy/stale data isn't silently dropped.
 */
function renderTraceField(args: {
  field: "unit" | "function";
  current: string;
  options: string[] | null;
  idAttrs: string;
}): string {
  const { field, current, options, idAttrs } = args;
  if (!options) {
    return `<input type="text" ${idAttrs} data-scope="trace" data-field="${field}" value="${escapeHtml(current)}">`;
  }
  const opts = [
    `<option value=""${current === "" ? " selected" : ""}>(none)</option>`,
  ];
  let found = current === "";
  for (const o of options) {
    const sel = o === current ? " selected" : "";
    if (o === current) found = true;
    opts.push(`<option value="${escapeHtml(o)}"${sel}>${escapeHtml(o)}</option>`);
  }
  if (!found) {
    opts.push(
      `<option value="${escapeHtml(current)}" selected>${escapeHtml(current)} (not in env)</option>`
    );
  }
  return `<select ${idAttrs} data-scope="trace" data-field="${field}">${opts.join("")}</select>`;
}

