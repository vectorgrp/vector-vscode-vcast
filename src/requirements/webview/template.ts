import * as vscode from "vscode";
import type {
  RGWBundle,
  RGWRequirement,
  RGWTraceabilityEntry,
} from "../rgwIo";

const path = require("path");

function escapeHtml(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;")
    .replace(/'/g, "&#39;");
}

/**
 * Render the grouped headings + cards for a bundle. Exported so the extension
 * can call it again after save/infer to refresh the headings — they reflect
 * the current `function || unit || source` grouping, which can change as the
 * user edits traceability.
 */
export function renderRequirementsBody(
  bundle: RGWBundle,
  unitsToFunctions: Record<string, string[]> | null
): string {
  const editable = bundle.origin.generated_by_reqs2x;

  const flat: Array<{
    source: string;
    id: string;
    req: RGWRequirement;
    trace: RGWTraceabilityEntry;
  }> = [];
  for (const [source, bucket] of Object.entries(bundle.requirements)) {
    for (const [id, req] of Object.entries(bucket)) {
      flat.push({
        source,
        id,
        req,
        trace: bundle.traceability[id] ?? {
          unit: null,
          function: null,
          lines: null,
        },
      });
    }
  }

  // Group by function, falling back to unit, then source.
  const groups: Record<string, typeof flat> = {};
  for (const entry of flat) {
    const key =
      entry.trace.function || entry.trace.unit || entry.source || "Unknown";
    if (!groups[key]) groups[key] = [];
    groups[key].push(entry);
  }

  let body = "";
  for (const [group, entries] of Object.entries(groups)) {
    body += `<h2>${escapeHtml(group)}</h2>`;
    for (const entry of entries) {
      body += renderCard(entry, editable, unitsToFunctions);
    }
  }
  return body;
}

/**
 * Build the full webview HTML. Loads CSS + JS from the `webviews/` media
 * folder via webview-relative URIs (a generated nonce gates `<script>`
 * execution). Initial state is injected as a `window.__rgwState` blob the
 * script picks up on load.
 */
export function generateRequirementsHtml(
  webview: vscode.Webview,
  webviewBaseDir: string,
  nonce: string,
  bundle: RGWBundle,
  unitsToFunctions: Record<string, string[]> | null = null
): string {
  const editable = bundle.origin.generated_by_reqs2x;

  const cssUri = webview.asWebviewUri(
    vscode.Uri.file(path.join(webviewBaseDir, "css", "requirements.css"))
  );
  const scriptUri = webview.asWebviewUri(
    vscode.Uri.file(
      path.join(webviewBaseDir, "webviewScripts", "requirements.js")
    )
  );

  const bannerHtml = editable
    ? `<div class="banner banner-editable">Editable — these requirements were generated by Reqs2X. Changes are saved back into the RGW.</div>`
    : `<div class="banner banner-readonly">Only traceability information can be updated with requirements exported from an external source (Polarion, DOORS, ...). Otherwise re-import could conflict with local changes.</div>`;

  const body = renderRequirementsBody(bundle, unitsToFunctions);

  const initialState = {
    gatewayPath: bundle.gatewayPath,
    editable,
    mtimes: bundle.mtimes,
    requirements: bundle.requirements,
    traceability: bundle.traceability,
    unitsToFunctions,
  };

  const cspSource = webview.cspSource;
  return `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src ${cspSource}; script-src 'nonce-${nonce}';">
<title>Requirements</title>
<link rel="stylesheet" href="${cssUri}">
</head>
<body>
<h1>Requirements</h1>
<div id="rgw-pill" title="${escapeHtml(bundle.gatewayPath)}">RGW: ${escapeHtml(bundle.gatewayPath)}</div>
${bannerHtml}
<div id="save-toolbar"><button id="infer-btn" title="Use the configured LLM to infer the unit/function each requirement traces to.">✨ Infer traceability</button><button id="save-btn" disabled>Save changes</button></div>
<div id="reqs-body">${body}</div>
<script nonce="${nonce}">window.__rgwState = ${JSON.stringify(initialState)};</script>
<script nonce="${nonce}" src="${scriptUri}"></script>
</body>
</html>`;
}

function renderCard(
  entry: {
    source: string;
    id: string;
    req: RGWRequirement;
    trace: RGWTraceabilityEntry;
  },
  editable: boolean,
  unitsToFunctions: Record<string, string[]> | null
): string {
  const idAttrs = `data-req-id="${escapeHtml(entry.id)}"`;
  const reqDis = editable ? "" : "disabled";
  const lastMod = entry.req.last_modified ?? "";

  return `
    <div class="req">
      <div class="req-header">
        <div class="req-id">${escapeHtml(entry.id)}</div>
        <div class="req-meta">${lastMod ? `modified: ${escapeHtml(lastMod)} · ` : ""}source: ${escapeHtml(entry.source)}</div>
      </div>
      <div class="field">
        <label>Title</label>
        <input type="text" ${idAttrs} data-scope="req" data-field="title" value="${escapeHtml(entry.req.title ?? "")}" ${reqDis}>
      </div>
      <div class="field">
        <label>Description</label>
        <textarea ${idAttrs} data-scope="req" data-field="description" ${reqDis}>${escapeHtml(entry.req.description ?? "")}</textarea>
      </div>
      <div class="field trace-row">
        <div>
          <label>Traceability: unit</label>
          ${renderUnitField(entry, idAttrs, unitsToFunctions)}
        </div>
        <div>
          <label>Traceability: function</label>
          ${renderFunctionField(entry, idAttrs, unitsToFunctions)}
        </div>
      </div>
    </div>
  `;
}

function renderUnitField(
  entry: { trace: RGWTraceabilityEntry },
  idAttrs: string,
  unitsToFunctions: Record<string, string[]> | null
): string {
  const current = entry.trace.unit ?? "";
  if (!unitsToFunctions) {
    return `<input type="text" ${idAttrs} data-scope="trace" data-field="unit" value="${escapeHtml(current)}">`;
  }
  const units = Object.keys(unitsToFunctions);
  const opts = [
    `<option value=""${current === "" ? " selected" : ""}>(none)</option>`,
  ];
  let found = current === "";
  for (const u of units) {
    const sel = u === current ? " selected" : "";
    if (u === current) found = true;
    opts.push(`<option value="${escapeHtml(u)}"${sel}>${escapeHtml(u)}</option>`);
  }
  if (!found) {
    opts.push(
      `<option value="${escapeHtml(current)}" selected>${escapeHtml(current)} (not in env)</option>`
    );
  }
  return `<select ${idAttrs} data-scope="trace" data-field="unit">${opts.join("")}</select>`;
}

function renderFunctionField(
  entry: { trace: RGWTraceabilityEntry },
  idAttrs: string,
  unitsToFunctions: Record<string, string[]> | null
): string {
  const current = entry.trace.function ?? "";
  if (!unitsToFunctions) {
    return `<input type="text" ${idAttrs} data-scope="trace" data-field="function" value="${escapeHtml(current)}">`;
  }
  const unit = entry.trace.unit ?? "";
  const fns = unit && unitsToFunctions[unit] ? unitsToFunctions[unit] : [];
  const opts = [
    `<option value=""${current === "" ? " selected" : ""}>(none)</option>`,
  ];
  let found = current === "";
  for (const f of fns) {
    const sel = f === current ? " selected" : "";
    if (f === current) found = true;
    opts.push(`<option value="${escapeHtml(f)}"${sel}>${escapeHtml(f)}</option>`);
  }
  if (!found) {
    opts.push(
      `<option value="${escapeHtml(current)}" selected>${escapeHtml(current)} (not in env)</option>`
    );
  }
  return `<select ${idAttrs} data-scope="trace" data-field="function">${opts.join("")}</select>`;
}

/**
 * Resolve the on-disk webview-resources directory. Mirrors the manage
 * webviews' resolution: normal install path first, then an E2E fallback
 * stripping the test-harness suffix.
 */
export function resolveRequirementsWebviewBase(
  context: vscode.ExtensionContext
): string {
  const fs = require("fs");
  const normal = path.join(
    context.extensionPath,
    "src",
    "requirements",
    "webviews"
  );
  if (fs.existsSync(normal)) return normal;

  const marker = path.join("tests", "internal", "e2e", "test", "extension");
  const idx = context.extensionPath.indexOf(marker);
  if (idx !== -1) {
    const repoRoot = context.extensionPath.slice(0, idx);
    const fallback = path.join(repoRoot, "src", "requirements", "webviews");
    if (fs.existsSync(fallback)) return fallback;
  }

  throw new Error(
    `Could not resolve requirements webview base. Tried:\n  ${normal}`
  );
}
